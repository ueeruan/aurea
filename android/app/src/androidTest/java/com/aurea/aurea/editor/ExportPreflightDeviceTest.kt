/** Real export preflight, platform encoder, gallery publication and independent decoder. */
class ExportPreflightDeviceTest {
    @get:Rule val compose = createComposeRule()

    @Test fun cancellingPreparationThenExporting1080KeepsTheSourceAndPublishesAllFrames() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        check(context.packageName.endsWith(".uitest")) { "Only the isolated test package may run this fixture" }
        val artifacts = File(context.getExternalFilesDir(null), "beta3-export-preflight/${SystemClock.elapsedRealtime()}")
        check(artifacts.mkdirs())
        val report = File(artifacts, "result.txt")
        @Suppress("DEPRECATION")
        val packageInfo = context.packageManager.getPackageInfo(context.packageName, 0)
        @Suppress("DEPRECATION")
        val versionCode = if (Build.VERSION.SDK_INT >= 28) packageInfo.longVersionCode else packageInfo.versionCode.toLong()
        report.writeText("package=${context.packageName} version=${packageInfo.versionName}/$versionCode " +
            "api=${Build.VERSION.SDK_INT} abi=${Build.SUPPORTED_ABIS.joinToString()} device=${Build.MODEL}\n")
        fun memory(label: String) {
            val info = ActivityManager.MemoryInfo()
            checkNotNull(context.getSystemService(ActivityManager::class.java)).getMemoryInfo(info)
            report.appendText("$label available=${info.availMem} total=${info.totalMem} lowMemory=${info.lowMemory}\n")
        }
        fun digest(file: File) = MessageDigest.getInstance("SHA-256").digest(file.readBytes())

        // This original is generated by the fixture and deliberately lives outside cache/.
        val source = File(context.filesDir, "beta3-export-own-source-${SystemClock.elapsedRealtime()}.png")
        val sourceBitmap = Bitmap.createBitmap(128, 128, Bitmap.Config.ARGB_8888)
        for (y in 0 until 128) for (x in 0 until 128)
            sourceBitmap.setPixel(x, y, Color.rgb(40 + x, 30 + y, 170))
        source.outputStream().use { assertTrue(sourceBitmap.compress(Bitmap.CompressFormat.PNG, 100, it)) }
        sourceBitmap.recycle()
        val originalDigest = digest(source)

        lateinit var store: EditorStore
        var ready = false
        compose.setContent {
            store = viewModel(factory = ViewModelProvider.AndroidViewModelFactory.getInstance(context.applicationContext as Application))
            ready = true
            AureaTheme { EditorScreen(store) }
        }
        compose.waitUntil(30000) { ready && store.engineReady }
        val title = "Beta3 export preflight ${SystemClock.elapsedRealtime()}"
        compose.runOnIdle { store.newProject(1920, 1080, 30f, title) }
        compose.waitUntil(15000) { store.project.title == title && !store.projectOperationBusy }
        compose.runOnIdle { store.importImage(Uri.fromFile(source)) }
        compose.waitUntil(15000) { store.layers.size == 1 && store.busyMessage == null }
        val imageId = store.layers.single().id
        compose.runOnIdle {
            repeat(4) { store.addShape(1) }
        }
        compose.waitUntil(15000) { store.layers.size == 5 }
        val layerIds = store.layers.map { it.id }.toSet()
        compose.runOnIdle {
            val engine = store.engineForStress
            engine.beginCommandBatch()
            val commands = CommandBatch(engine)
            store.layers.forEachIndexed { n, layer ->
                commands.setLayerTimeRange(layer.id, 0, 12)
                if (layer.id != imageId) {
                    commands.setShapeFill(layer.id, .15f, .8f, .3f, 1f)
                    commands.setPosition(layer.id, 760f + n * 75f, 540f, 0f)
                }
            }
            assertTrue(engine.submitCommands() > 0)
            // Each trim may extend composition length while other clips still
            // have their default end. Set the intended length after every trim.
            store.setCompositionDuration(12)
            store.seek(3)
        }
        compose.waitUntil(15000) {
            store.layers.all { it.endFrame == 12 } && store.composition?.durationFrames == 12 &&
                store.engineForStress.exportDuration(false) == 12L
        }
        report.appendText("setup composition=${store.composition?.durationFrames} nativeExportDuration=${store.engineForStress.exportDuration(false)} " +
            "clipEnds=${store.layers.map { it.endFrame }}\n")
        memory("preview-before")
        val exportCache = File(context.cacheDir, "export").apply { check(isDirectory || mkdirs()) }
        report.appendText("exportRoot=${exportCache.absolutePath} canonical=${exportCache.canonicalPath}\n")
        val orphan = File(exportCache, "beta3-owned-orphan-probe-${SystemClock.elapsedRealtime()}.mp4")
        orphan.writeText("Own fixture orphan, never a source or a current writer")
        // The app's startup sweep predates this fixture. Keep this file newer
        // than that session so its disappearance proves export-time cleanup.
        assertTrue(orphan.setLastModified(System.currentTimeMillis() + 60000L))
        assertTrue(orphan.isFile)
        val options = ExportOptions(shortSide = 1080, fps = 30.0, hevc = false, trimToContent = false)

        // The UI publishes preparation synchronously, so this cancellation belongs
        // to startup rather than to a later percent or a previous export session.
        compose.runOnIdle {
            store.exporter.start("Beta3 cancelled preparation", 1920, 1080, 30.0, options)
            assertTrue(store.exporter.busy)
            assertTrue(store.exporter.state.preparing)
            assertTrue(store.exporter.state.notice.isNotBlank())
            store.exporter.cancel()
        }
        compose.waitUntil(90000) { !store.exporter.busy }
        assertEquals(store.exporter.state.message, ExportPhase.Cancelled, store.exporter.state.phase)
        assertFalse(store.exporter.state.preparing)
        assertNull(store.exporter.state.outputUri)
        assertArrayEquals("Preparation must preserve the original file", originalDigest, digest(source))
        report.appendText("cancel=Cancelled originalPreserved=true layers=${store.layers.size}\n")

        // Leave an active preview request before export takes ownership again.
        compose.runOnIdle { store.seek(4); store.play() }
        val started = SystemClock.elapsedRealtime()
        compose.runOnIdle { store.exporter.start("Beta3 published 1080", 1920, 1080, 30.0, options) }
        var maxFrames = 0
        compose.waitUntil(180000) {
            maxFrames = maxOf(maxFrames, store.exporter.state.framesDone)
            !store.exporter.busy
        }
        val state = store.exporter.state
        report.appendText("export=${state.phase} elapsedMs=${SystemClock.elapsedRealtime() - started} " +
            "frames=${state.framesDone}/${state.framesTotal} maxObserved=$maxFrames preparing=${state.preparing} " +
            "message=${state.message}\n")
        assertEquals(state.message, ExportPhase.Done, state.phase)
        assertFalse(state.preparing)
        report.appendText("ownedOrphanRemoved=${!orphan.exists()}\n")
        assertFalse("Export preparation must remove its owned orphan output", orphan.exists())
        assertEquals("Every frame must leave 0% and complete", 12, state.framesDone)
        assertEquals(12, state.framesTotal)
        assertTrue(maxFrames > 0)
        val uri = checkNotNull(state.outputUri)
        assertEquals("content", uri.scheme)
        val output = File(artifacts, "published-1920x1080-h264.mp4")
        context.contentResolver.openInputStream(uri)!!.use { input -> output.outputStream().use { input.copyTo(it) } }
        assertTrue("Published MP4 must be readable", output.length() > 1000)
        assertNotNull(store.exporter.shareIntent())
        assertArrayEquals("Export cleanup must preserve the original file", originalDigest, digest(source))
        assertEquals(layerIds, store.layers.map { it.id }.toSet())
        assertEquals(12, store.project.durationFrames)

        fun verifyVideo(videoFile: File, label: String) {
            val extractor = MediaExtractor()
            try {
                extractor.setDataSource(videoFile.absolutePath)
                val video = (0 until extractor.trackCount).map { extractor.getTrackFormat(it) }
                    .first { it.getString(MediaFormat.KEY_MIME)?.startsWith("video/") == true }
                assertEquals("video/avc", video.getString(MediaFormat.KEY_MIME))
                assertEquals(1920, video.getInteger(MediaFormat.KEY_WIDTH))
                assertEquals(1080, video.getInteger(MediaFormat.KEY_HEIGHT))
                report.appendText("$label independentTrack=$video\n")
            } finally { extractor.release() }
            val reader = MediaMetadataRetriever()
            try {
                reader.setDataSource(videoFile.absolutePath)
                val duration = checkNotNull(reader.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION)).toLong()
                assertTrue("Twelve 30fps frames must have a short, nonzero duration: $duration", duration in 300L..600L)
                for (time in listOf(0L, 11L * 1000000L / 30L)) {
                    val decoded = checkNotNull(reader.getFrameAtTime(time, MediaMetadataRetriever.OPTION_CLOSEST))
                    try {
                        var lit = 0
                        var sampled = 0
                        for (y in 0 until decoded.height step 16) for (x in 0 until decoded.width step 16) {
                            val pixel = decoded.getPixel(x, y)
                            if (maxOf(Color.red(pixel), Color.green(pixel), Color.blue(pixel)) > 32) lit++
                            sampled++
                        }
                        assertTrue("The independently decoded frame must contain the own image/shapes", lit > sampled / 100)
                        File(artifacts, "$label-decoded-$time.png").outputStream().use { decoded.compress(Bitmap.CompressFormat.PNG, 100, it) }
                        report.appendText("$label decodedUs=$time size=${decoded.width}x${decoded.height} lit=$lit/$sampled\n")
                    } finally { decoded.recycle() }
                }
                report.appendText("$label durationMs=$duration bytes=${videoFile.length()}\n")
            } finally { reader.release() }
        }
        verifyVideo(output, "image-shapes")
        report.appendText("publishedUri=$uri originalPreserved=true\n")

        // Reuse only this fixture's own published MP4 as a source. This second
        // pass traverses preview codec retirement and an offline video opener;
        // cleanup must keep the imported source/cache alive for that opener.
        val videoDigest = digest(output)
        compose.runOnIdle { store.pause(); store.importVideo(uri) }
        compose.waitUntil(30000) { store.layers.size == 6 && store.busyMessage == null }
        val importedVideo = store.layers.single { it.id !in layerIds }.id
        compose.runOnIdle {
            val engine = store.engineForStress
            engine.beginCommandBatch()
            CommandBatch(engine).setLayerTimeRange(importedVideo, 0, 12)
            assertTrue(engine.submitCommands() > 0)
            store.setCompositionDuration(12)
            store.seek(5)
        }
        compose.waitUntil(10000) { store.playhead == 5 && store.project.durationFrames == 12 }
        val videoLayerIds = store.layers.map { it.id }.toSet()
        val videoStarted = SystemClock.elapsedRealtime()
        compose.runOnIdle { store.exporter.start("Beta3 owned video reexport 1080", 1920, 1080, 30.0, options) }
        compose.waitUntil(180000) { !store.exporter.busy }
        val videoState = store.exporter.state
        report.appendText("videoReexport=${videoState.phase} elapsedMs=${SystemClock.elapsedRealtime() - videoStarted} " +
            "frames=${videoState.framesDone}/${videoState.framesTotal} message=${videoState.message}\n")
        assertEquals(videoState.message, ExportPhase.Done, videoState.phase)
        assertEquals(12, videoState.framesDone)
        assertEquals(12, videoState.framesTotal)
        assertFalse(videoState.preparing)
        assertEquals(videoLayerIds, store.layers.map { it.id }.toSet())
        val videoUri = checkNotNull(videoState.outputUri)
        val reexport = File(artifacts, "reexport-owned-video-1920x1080-h264.mp4")
        context.contentResolver.openInputStream(videoUri)!!.use { input -> reexport.outputStream().use { input.copyTo(it) } }
        assertTrue(reexport.length() > 1000)
        verifyVideo(reexport, "video-reexport")
        assertArrayEquals("Video preparation must not alter its original", videoDigest, digest(output))
        val publishedSourceDigest = context.contentResolver.openInputStream(uri)!!.use {
            MessageDigest.getInstance("SHA-256").digest(it.readBytes())
        }
        assertArrayEquals("Cleanup must retain the own published source", videoDigest, publishedSourceDigest)
        assertArrayEquals(originalDigest, digest(source))
        report.appendText("videoPublishedUri=$videoUri videoSourcePreserved=true\n")
        memory("exports-after")
        compose.runOnIdle { store.pause(); store.seek(3) }
        compose.waitUntil(10000) { !store.playing && store.playhead == 3 }
        report.appendText("previewResumed=true result=PASS\n")
    }
}
