//  Isso e deliberado: um texto novo entra nos dois sistemas pelo mesmo nome,
//  e o catalogo continua sendo um so (o do Android e a fonte).
//
//  O Android tem SETE idiomas (values/ = pt-BR + ar, en, es, hi, id, ru). Esta
//  entrega traz pt-BR e ingles — os outros cinco saem do mesmo XML, pela mesma
//  extracao, quando o dono quiser (ver README).
