import Foundation

/// Um idioma do app. O que o dono escolhe nos Ajustes; o padrao segue o sistema.
enum AureaLanguage: String, CaseIterable, Identifiable {
    case pt = "pt-BR"
    case en = "en"

    var id: String { rawValue }

    /// Rotulo do seletor. Nome do idioma NO idioma — nao traduzido.
    var label: String {
        switch self {
        case .pt: return "Português (Brasil)"
        case .en: return "English"
        }
    }

    /// Idioma do sistema quando ele e um dos que temos; senao pt-BR (o idioma
    /// em que o app foi escrito, e o mesmo padrao do Android).
    static var systemDefault: AureaLanguage {
        for code in Locale.preferredLanguages {
            if code.hasPrefix("en") { return .en }
            if code.hasPrefix("pt") { return .pt }
        }
        return .pt
    }
}

/// O catalogo. `t()` traduz; chave desconhecida devolve a propria chave, o que
/// aparece na tela em vez de um texto vazio — um furo de traducao fica visivel.
enum AureaText {
    /// Idioma em vigor. O modelo observa e redesenha quando muda.
    static var language: AureaLanguage = .systemDefault

    static func t(_ key: String) -> String {
        let table = language == .en ? en : pt
        return table[key] ?? pt[key] ?? key
    }

    static func t(_ key: String, _ args: CVarArg...) -> String {
        String(format: t(key), arguments: args)
    }

